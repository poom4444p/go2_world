"""Export Cyberdog's building into go2_world, once: assets/building.xml.

Cyberdog (the cyberdog_jetson repo, next to this one; CYBERDOG= to point
elsewhere) builds its scene from the planner's occupancy grids and caches it
in output/scene_cache/building.xml (python -m cyberdog.sim.scene.build_scene
--building). go2_world takes a frozen copy of
that cache, so the world the dog walks in does not change under it when the
brain repo does. Run this again only to take a newer building on purpose.

What is kept: every static geom (slabs, walls, stairs, obstacles), the lift
car's floor and roof frozen where they stand (on floor 1), and the lights.
What is dropped: Cyberdog's own Go2 (menagerie's, not unitree_mujoco's), its
camera, and the pedestrians, which are mocap bodies parked 50 m underground
until Cyberdog moves them.

Everything is shifted by -SPAWN, so the place the Go2 starts in unitree_mujoco
(the origin) is a free spot in the floor 1 corridor. Building map coordinates
are world + SPAWN.

  python tools/export_building.py [path/to/building.xml]
"""
import os
import sys
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
CYBERDOG = os.environ.get("CYBERDOG") or os.path.join(HERE, "..", "..", "cyberdog_jetson")
SRC = os.path.normpath(os.path.join(CYBERDOG, "output", "scene_cache", "building.xml"))
OUT = os.path.join(HERE, "..", "assets", "building.xml")
SPAWN = (21.0, 9.5, 0.0)          # floor 1 corridor, 2.4 m short of the trolley
CLEAR = 0.5                       # nothing solid this close to the spawn point


def shift(pos, by):
    return " ".join(f"{float(v) + d:.3f}" for v, d in zip(pos.split(), by))


def blocks_spawn(geom):
    """True for a box that comes within CLEAR of the spawn point, 0.1 to 0.6 m up."""
    if geom.get("type") != "box":
        return False
    p = [float(v) for v in geom.get("pos").split()]
    s = [float(v) for v in geom.get("size").split()]
    return (abs(p[0]) < s[0] + CLEAR and abs(p[1]) < s[1] + CLEAR
            and p[2] - s[2] < 0.6 and p[2] + s[2] > 0.1)


def export(src=SRC, out=OUT):
    world = ET.parse(src).getroot().find("worldbody")
    to_origin = tuple(-v for v in SPAWN)
    keep = []
    for el in world:
        if el.tag in ("geom", "light"):
            el.set("pos", shift(el.get("pos"), to_origin))
            keep.append(el)
        elif el.tag == "body" and el.get("name") == "lift_car":
            at = shift(el.get("pos"), to_origin)
            for g in el.findall("geom"):
                g.set("pos", shift(g.get("pos"), tuple(float(v) for v in at.split())))
                keep.append(g)

    walls = [g for g in keep if g.tag == "geom"]
    hit = [g.get("name") for g in walls if blocks_spawn(g)]
    if hit:
        raise SystemExit(f"spawn {SPAWN} is not clear: {hit}")

    root = ET.Element("mujoco", model="go2_world_building")
    root.append(ET.Comment(f" generated by tools/export_building.py from {src}; "
                           f"map frame = this frame + {SPAWN} "))
    body = ET.SubElement(root, "worldbody")
    body.extend(keep)
    ET.indent(root)
    ET.ElementTree(root).write(out, encoding="unicode")
    print(f"{len(walls)} geoms -> {os.path.normpath(out)}")


if __name__ == "__main__":
    export(*sys.argv[1:2])
